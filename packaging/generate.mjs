#!/usr/bin/env node
// Writes a Homebrew formula (overfull.rb) and a Scoop manifest (overfull.json) for one
// release, from that release's SHA256SUMS. The release workflow attaches both files to the
// GitHub release; copy them into a tap (homebrew-overfull/Formula/overfull.rb) and a bucket
// (scoop-overfull/bucket/overfull.json). See packaging/README.md.
//
//   node packaging/generate.mjs --version 3.1.0 --sums assets/SHA256SUMS --out assets
//
// No dependencies, so it runs on a bare runner.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseArgs } from 'node:util';

export const REPO = 'amet13/overfull';
const DESC = 'Preflight checks for LaTeX papers and theses';
const HOMEPAGE = 'https://amet13.github.io/overfull/';

/** `<sha256>  <file>` lines → Map(file → sha256). Rejects anything that is not a checksum line. */
export function parseSums(text) {
  const sums = new Map();
  for (const line of text.split('\n')) {
    if (!line.trim()) continue;
    const m = /^([0-9a-f]{64}) [ *]?(\S+)$/.exec(line.trim());
    if (!m) throw new Error(`not a SHA256SUMS line: ${line.slice(0, 80)}`);
    sums.set(m[2], m[1]);
  }
  return sums;
}

function need(sums, file) {
  const sum = sums.get(file);
  if (!sum) throw new Error(`SHA256SUMS has no entry for ${file}`);
  return sum;
}

export function formula(version, sums) {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`not a version: ${version}`);
  const url = (f) => `https://github.com/${REPO}/releases/download/v${version}/${f}`;
  const block = (f) => [`      url "${url(f)}"`, `      sha256 "${need(sums, f)}"`].join('\n');
  return `# Generated by packaging/generate.mjs for Overfull v${version}. Do not edit by hand.
class Overfull < Formula
  desc "${DESC}"
  homepage "${HOMEPAGE}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${block('overfull-darwin-arm64')}
    end
    on_intel do
${block('overfull-darwin-x64')}
    end
  end

  on_linux do
    on_arm do
${block('overfull-linux-arm64')}
    end
    on_intel do
${block('overfull-linux-x64')}
    end
  end

  def install
    bin.install Dir["overfull-*"].first => "overfull"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/overfull --version")
  end
end
`;
}

export function scoop(version, sums) {
  if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`not a version: ${version}`);
  const base = `https://github.com/${REPO}/releases/download`;
  return `${JSON.stringify(
    {
      version,
      description: DESC,
      homepage: HOMEPAGE,
      license: 'MIT',
      architecture: {
        '64bit': {
          url: `${base}/v${version}/overfull-win-x64.exe#/overfull.exe`,
          hash: need(sums, 'overfull-win-x64.exe'),
        },
      },
      bin: 'overfull.exe',
      checkver: { github: `https://github.com/${REPO}` },
      autoupdate: {
        architecture: {
          '64bit': { url: `${base}/v$version/overfull-win-x64.exe#/overfull.exe` },
        },
        hash: { url: '$baseurl/SHA256SUMS' },
      },
    },
    null,
    2,
  )}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { values } = parseArgs({
    options: {
      version: { type: 'string' },
      sums: { type: 'string' },
      out: { type: 'string', default: '.' },
    },
  });
  if (!values.version || !values.sums) {
    console.error(
      'Usage: node packaging/generate.mjs --version X.Y.Z --sums SHA256SUMS [--out dir]',
    );
    process.exit(2);
  }
  const sums = parseSums(readFileSync(values.sums, 'utf8'));
  writeFileSync(join(values.out, 'overfull.rb'), formula(values.version, sums));
  writeFileSync(join(values.out, 'overfull.json'), scoop(values.version, sums));
  console.log(`wrote overfull.rb and overfull.json for v${values.version}`);
}
